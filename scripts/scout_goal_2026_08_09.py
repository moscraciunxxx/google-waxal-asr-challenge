def checkpoint_inventory() -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    for config in sorted((ROOT / "checkpoints").rglob("config.json")):
        model = config.parent / "model.safetensors"
        if not model.is_file():
            continue
        rows.append(
            {
                "path": str(config.parent.relative_to(ROOT)),
                "config_sha256": sha256(config),
                "model_size_bytes": model.stat().st_size,
                "model_sha256": None,
                "model_hash_status": "not_rehashed_in_scout_156GB_checkpoint_tree",
            }
        )
    return rows


