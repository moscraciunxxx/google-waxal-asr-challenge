def sha256(path: Path) -> str | None:
    if not path.is_file():
        return None
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def load_json(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text())


def metric(n: int, wer: float, cer: float, zindi: float) -> dict[str, float | int]:
    return {"n": n, "wer": wer, "cer": cer, "zindi": zindi}


def delta(candidate: dict[str, Any], incumbent: dict[str, Any]) -> float:
    return float(candidate["zindi"]) - float(incumbent["zindi"])


